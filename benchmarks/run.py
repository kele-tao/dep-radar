"""Benchmark dep-radar on synthetic lockfiles of increasing size.

Generates a deterministic npm v3 lockfile, then measures the full pipeline
(parse -> build graph -> analyse -> render). Writes benchmarks/results.json and
benchmarks/RESULTS.md, which the README table quotes verbatim. No network, no
randomness: rerunning produces the same tree.

  python benchmarks/run.py
  python benchmarks/run.py --sizes 100,500,1000 --json
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from dep_radar.analyzer import analyze  # noqa: E402
from dep_radar.parsers import parse_ecosystem  # noqa: E402
from dep_radar.report import render_json, render_terminal  # noqa: E402

RESULTS_JSON = ROOT / "benchmarks" / "results.json"
RESULTS_MD = ROOT / "benchmarks" / "RESULTS.md"


LAYER_WIDTH = 60
DIRECT_COUNT = 10  # a real app has a handful of direct dependencies


def build_tree(size: int, root: Path) -> Path:
    """Write a deterministic, layered npm project with *size* locked packages.

    Packages sit in layers of LAYER_WIDTH; every package depends on two
    packages of the next layer, so the graph fans out like a real bundled tree
    (depth ~ size / width) instead of a 1000-wide star. Only the first
    DIRECT_COUNT packages are declared in package.json.
    """
    packages: dict = {"": {"name": "bench-app", "version": "1.0.0", "dependencies": {}}}
    for index in range(size):
        name = "bench-pkg-" + str(index)
        layer = index // LAYER_WIDTH
        next_start = (layer + 1) * LAYER_WIDTH
        next_size = max(0, min(LAYER_WIDTH, size - next_start))
        deps: dict[str, str] = {}
        if next_size:
            for offset in (0, 1):
                target = next_start + (2 * (index % LAYER_WIDTH) + offset) % next_size
                deps["bench-pkg-" + str(target)] = "^1.0.0"
        packages["node_modules/" + name] = {
            "version": "1.0.0",
            "name": name,
            "license": "MIT" if index % 7 else "GPL-3.0",
            "resolved": "https://registry.npmjs.org/" + name + "/-/" + name + "-1.0.0.tgz",
            "integrity": "sha512-" + "A" * 86,
            "dependencies": deps,
        }
        if index < DIRECT_COUNT:
            packages[""]["dependencies"][name] = "^1.0.0"
    (root / "package.json").write_text(
        json.dumps({"name": "bench-app", "dependencies": packages[""]["dependencies"]}),
        encoding="utf-8",
    )
    (root / "package-lock.json").write_text(
        json.dumps(
            {"name": "bench-app", "version": "1.0.0", "lockfileVersion": 3, "packages": packages}
        ),
        encoding="utf-8",
    )
    return root


def time_once(path: Path) -> float:
    started = time.perf_counter()
    project = parse_ecosystem(path, "npm")
    analysis = analyze(project, root=path, scan_sources_flag=False)
    render_terminal(analysis, top=200)
    render_json(analysis)
    return (time.perf_counter() - started) * 1000.0


def measure(size: int, repeats: int) -> dict:
    with tempfile.TemporaryDirectory() as tmp:
        root = build_tree(size, Path(tmp))
        lock_bytes = (root / "package-lock.json").stat().st_size
        time_once(root)  # warm the page cache and the import path
        samples = [time_once(root) for _ in range(repeats)]
        analysis = analyze(parse_ecosystem(root, "npm"), root=root, scan_sources_flag=False)
    return {
        "packages": size,
        "lockfile_kb": round(lock_bytes / 1024, 1),
        "median_ms": round(statistics.median(samples), 2),
        "min_ms": round(min(samples), 2),
        "max_ms": round(max(samples), 2),
        "findings": len(analysis.findings),
        "max_depth": analysis.stats.max_depth,
        "score": analysis.score,
    }


def render_markdown(results: list[dict], environment: dict) -> str:
    lines = [
        "# Benchmark results",
        "",
        "Generated by `python benchmarks/run.py`. Every number below comes from that",
        "command; the README table is a copy of this file.",
        "",
        "| Packages | Lockfile | Median (ms) | Min (ms) | Max (ms) | Max depth | Findings |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in results:
        lines.append(
            "| {packages} | {lockfile_kb} KB | {median_ms} | {min_ms} | {max_ms} | "
            "{max_depth} | {findings} |".format(**row)
        )
    lines += [
        "",
        "Environment: Python {python} on {system}, {machine}, {cpu} cores.".format(**environment),
        "",
        "The pipeline measured is: parse package.json + package-lock.json v3, build the",
        "dependency graph, run every risk check, render the terminal report and the JSON",
        "document. Source import scanning is excluded (it depends on repository size, not",
        "on the dependency tree).",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sizes", default="100,500,1000,2000", help="comma separated package counts")
    parser.add_argument("--repeats", type=int, default=5, help="timed runs per size (median reported)")
    parser.add_argument("--json", action="store_true", help="print the raw results as JSON")
    args = parser.parse_args()
    sizes = [int(part) for part in args.sizes.split(",") if part.strip()]
    results = [measure(size, args.repeats) for size in sizes]
    environment = {
        "python": platform.python_version(),
        "system": platform.system(),
        "machine": platform.machine(),
        "cpu": os_cpu_count(),
    }
    payload = {"environment": environment, "repeats": args.repeats, "results": results}
    RESULTS_JSON.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    RESULTS_MD.write_text(render_markdown(results, environment), encoding="utf-8")
    if args.json:
        print(json.dumps(payload, indent=2))
    else:
        print(render_markdown(results, environment))
    return 0


def os_cpu_count() -> int:
    import os

    return os.cpu_count() or 1


if __name__ == "__main__":
    raise SystemExit(main())
